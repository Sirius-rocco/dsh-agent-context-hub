function pushMessage(messages, message) {
  const text = String(message.text ?? '')
  if (!text.trim()) return
  messages.push({ ...message, text })
}

/** 用户正文：先剥掉拼在开头的注入块，剩下的仍是注入或空串就整条丢掉。 */
function pushUserText(messages, raw, ts) {
  const text = stripInjectionBlocks(raw)
  if (!text.trim() || isInjectedText(text)) return
  const clamped = clampText(text, TEXT_LIMIT)
  pushMessage(messages, {
    role: 'user',
    kind: 'message',
    ts,
    name: null,
    text: clamped.text,
    truncated: clamped.truncated,
  })
}

function appendUserLine(entry, messages, toolNames) {
  const ts = normalizeIso(entry.timestamp)
  const content = entry.message?.content
  if (!Array.isArray(content)) {
    if (typeof content === 'string') pushUserText(messages, content, ts)
    return
  }
  for (const block of content) {
    if (!block || typeof block !== 'object') continue
    if (block.type === 'tool_result') {
      const clamped = clampText(toolResultText(block.content), TOOL_OUTPUT_LIMIT)
      pushMessage(messages, {
        role: 'tool',
        kind: 'tool_output',
        ts,
        name: toolNames.get(block.tool_use_id) ?? null,
        text: clamped.text,
        truncated: clamped.truncated,
      })
      continue
    }
    // image 块没有可读文本；tool_use 只出现在 assistant 行里。
    if (block.type === 'text' && typeof block.text === 'string') pushUserText(messages, block.text, ts)
  }
}

/** 工具参数摘要：shell 类工具取 command，其它保留完整 JSON（截断兜底）。 */
function summarizeToolInput(name, input) {
  if (input === null || input === undefined) return ''
  if (typeof input === 'string') return input
  if (SHELL_TOOLS.has(name) && typeof input.command === 'string') return input.command
  return JSON.stringify(input)
}

function appendAssistantLine(entry, messages, toolNames) {
  const ts = normalizeIso(entry.timestamp)
  const content = entry.message?.content
  if (typeof content === 'string') {
    const clamped = clampText(content, TEXT_LIMIT)
    pushMessage(messages, {
      role: 'assistant',
      kind: 'message',
      ts,
      name: null,
      text: clamped.text,
      truncated: clamped.truncated,
    })
    return
  }
  if (!Array.isArray(content)) return
  for (const block of content) {
    if (!block || typeof block !== 'object') continue
    if (block.type === 'text' && typeof block.text === 'string') {
      const clamped = clampText(block.text, TEXT_LIMIT)
      pushMessage(messages, {
        role: 'assistant',
        kind: 'message',
        ts,
        name: null,
        text: clamped.text,
        truncated: clamped.truncated,
      })
      continue
    }
    if (block.type === 'tool_use') {
      const name = typeof block.name === 'string' && block.name ? block.name : 'tool'
      // 结果行只带 tool_use_id，先记下 id→name，正文里才能显示工具名。
      if (typeof block.id === 'string' && block.id) toolNames.set(block.id, name)
      const clamped = clampText(summarizeToolInput(name, block.input), TOOL_OUTPUT_LIMIT)
      pushMessage(messages, {
        role: 'tool',
        kind: 'tool_call',
        ts,
        name,
        text: clamped.text,
        truncated: clamped.truncated,
      })
      continue
    }
    // thinking / redacted_thinking：思维链既不展示也不占正文配额，直接丢弃。
  }
}

export async function readTranscript(session, ctx = {}) {
  const file = typeof session?.file === 'string' && session.file ? session.file : null
  if (!file) {
    const error = new Error('该会话没有本地文件，无法读取正文')
    error.code = 'ENOENT'
    throw error
  }
  const maxMessages =
    Number.isInteger(ctx.maxMessages) && ctx.maxMessages > 0 ? ctx.maxMessages : DEFAULT_MAX_MESSAGES

  const result = emptyTranscript(file)
  result.id = session.id ?? null
  result.title = session.title ?? null
  result.cwd = session.cwd ?? null
  result.model = session.model ?? null
  result.createdAt = session.createdAt ?? null
  result.updatedAt = session.updatedAt ?? null

  const messages = []
  const toolNames = new Map()
  let badLines = 0
  let truncated = false

  // 流式读：单份 jsonl 可以到上百 MB，readline 会把跨块的多字节字符拼回来。
  const stream = fs.createReadStream(file, { encoding: 'utf8' })
  const rl = readline.createInterface({ input: stream, crlfDelay: Infinity })
  try {
    for await (const line of rl) {
      if (!line.trim()) continue
      const entry = parseLine(line)
      if (entry === BAD_LINE) {
        badLines += 1
        continue
      }
      if (!entry || typeof entry !== 'object' || Array.isArray(entry)) continue

      // 索引只读了头部，model 这类字段在尾部才出现时这里补上。
      if (!result.cwd && typeof entry.cwd === 'string' && entry.cwd) result.cwd = entry.cwd
      if (!result.model && typeof entry.message?.model === 'string' && entry.message.model) {
        result.model = entry.message.model
      }

      if (entry.type === 'user') {
        if (entry.isMeta === true || entry.isSidechain === true) continue
        appendUserLine(entry, messages, toolNames)
      } else if (entry.type === 'assistant') {
        if (entry.isSidechain === true) continue
        appendAssistantLine(entry, messages, toolNames)
      }
      // system / summary / queue-operation / file-history-snapshot 都不是正文。

      if (messages.length >= maxMessages) {
        if (messages.length > maxMessages) messages.length = maxMessages
        truncated = true
        break
      }
    }
  } finally {
    rl.close()
    stream.destroy()
  }

  result.messages = messages
  result.messageCount = messages.length
  result.userPromptCount = messages.filter((message) => message.role === 'user').length
  result.hasToolCalls = messages.some((message) => message.kind === 'tool_call')
  result.truncated = truncated
  result.badLines = badLines
  return result
}
