function newInfo() {
  return {
    id: null,
    cwd: null,
    createdAt: null,
    model: null,
    version: null,
    gitBranch: null,
    summaryTitle: '',
    prompts: [],
    badLines: 0,
  }
}

/**
 * 把一段文本里的行合并进 info。head 与 tail 走同一条路径：
 * head 只取「第一次出现」的元数据，tail 只补最近的提问，summary 后读到的覆盖先读到的。
 *
 * `cutTail` 丢掉被窗口截断的最后半行（那是切出来的，不是畸形行）；
 * `dropFirstLine` 丢掉尾部窗口起点的半行；`countBad` 用来避免头尾窗口重叠时重复计数。
 */
function applyLines(text, info, opts = {}) {
  let body = text
  if (opts.cutTail) {
    const cut = body.lastIndexOf('\n')
    body = cut === -1 ? '' : body.slice(0, cut)
  }
  if (opts.dropFirstLine) {
    const first = body.indexOf('\n')
    body = first === -1 ? '' : body.slice(first + 1)
  }
  for (const line of body.split('\n')) {
    if (!line.trim()) continue
    const entry = parseLine(line)
    if (entry === BAD_LINE) {
      if (opts.countBad !== false) info.badLines += 1
      continue
    }
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) continue

    if (info.id === null && typeof entry.sessionId === 'string' && entry.sessionId.trim()) {
      info.id = entry.sessionId.trim()
    }
    if (info.cwd === null && typeof entry.cwd === 'string' && entry.cwd.trim()) info.cwd = entry.cwd
    if (info.createdAt === null) info.createdAt = normalizeIso(entry.timestamp)
    if (info.version === null && typeof entry.version === 'string' && entry.version) info.version = entry.version
    if (info.gitBranch === null && typeof entry.gitBranch === 'string' && entry.gitBranch) {
      info.gitBranch = entry.gitBranch
    }
    if (info.model === null && typeof entry.message?.model === 'string' && entry.message.model) {
      info.model = entry.message.model
    }
    // summary 行是会话的短标题；出现多条（多次压缩）时取最后一条，最接近当前状态。
    if (entry.type === 'summary' && typeof entry.summary === 'string' && entry.summary.trim()) {
      info.summaryTitle = titleFromText(entry.summary)
    }
    if (entry.type === 'user') {
      const prompt = promptText(entry)
      if (prompt) info.prompts.push(prompt)
    }
  }
  return info
}

/** 读文件尾部窗口（base.mjs 只有头部读取，尾部要自己开句柄）。 */
async function readTailBytes(file, bytes, size) {
  const length = Math.min(bytes, size)
  if (length <= 0) return ''
  const handle = await fsp.open(file, 'r')
  try {
    const buffer = Buffer.alloc(length)
    const { bytesRead } = await handle.read(buffer, 0, length, size - length)
    return buffer.subarray(0, bytesRead).toString('utf8')
  } finally {
    await handle.close()
  }
}

function buildExtra(info, projectDir, cwdGuessed) {
  const extra = {}
  if (info.version) extra.version = info.version
  if (info.gitBranch) extra.gitBranch = info.gitBranch
  if (projectDir) extra.projectDir = projectDir
  // 反解出来的 cwd 是猜测，标出来，正文页别让人当成真实路径。
  if (cwdGuessed) extra.cwdGuessed = true
  return Object.keys(extra).length > 0 ? extra : null
}

/**
 * 扫一个 jsonl。返回 `{ row, badLines, bytesRead }`：统计值单独返回，
 * 免得非契约字段混进会话行。
 */
async function scanFile(file, opts) {
  const stat = await fsp.stat(file)
  const info = newInfo()
  applyLines(await readHeadBytes(file, HEAD_BYTES), info, { cutTail: stat.size > HEAD_BYTES })
  const headCount = info.prompts.length
  let bytesRead = Math.min(stat.size, HEAD_BYTES)

  if (stat.size > HEAD_BYTES) {
    // 只有头部窗口时最近的提问一条都搜不到，所以补一次固定成本的尾部读。
    // 头尾窗口可能重叠，重叠时尾部不重复计畸形行，避免一个坏行数成两行。
    const overlap = stat.size <= HEAD_BYTES + TAIL_BYTES
    applyLines(await readTailBytes(file, TAIL_BYTES, stat.size), info, {
      dropFirstLine: true,
      countBad: !overlap,
    })
    bytesRead += Math.min(stat.size, TAIL_BYTES)
  }

  // --deep 才做全量畸形行计数；默认只数头部窗口，扫描保持廉价。
  const badLines = opts.deep ? (await readJsonl(file, () => {})).badLines : info.badLines

  const projectDir = path.basename(path.dirname(file))
  const max = opts.maxPrompts
  const headPrompts = info.prompts.slice(0, headCount)
  const tailPrompts = info.prompts.slice(headCount)
  // 最早与最近各留一半：只用头部会丢掉「最近的提问」，只用尾部会丢掉开场白。
  let headTake = Math.min(headPrompts.length, Math.ceil(max / 2))
  let tailTake = Math.min(tailPrompts.length, Math.floor(max / 2))
  // 一侧窗口的提问常常远少于半份（长会话的尾部可能只有收尾一句），不补就会出现
  // 「文件里明明有 30 条提问却只出 11 条」的欠计数；补齐时仍保持两侧各自的顺序。
  const shortfall = max - headTake - tailTake
  if (shortfall > 0) {
    const extraHead = Math.min(shortfall, headPrompts.length - headTake)
    headTake += extraHead
    tailTake += Math.min(shortfall - extraHead, tailPrompts.length - tailTake)
  }
  const prompts = mergePrompts(
    headPrompts.slice(0, headTake),
    tailTake > 0 ? tailPrompts.slice(-tailTake) : [],
  ).slice(0, max)

  const cwd = info.cwd ?? cwdFromProjectDir(projectDir)
  const row = {
    // Every adapter stamps its own id; hub.scanAll merges rows as-is.
    agent: meta.id,
    id: info.id ?? path.basename(file, '.jsonl'),
    title: info.summaryTitle || titleFromText(prompts[0] ?? '') || null,
    cwd,
    file,
    createdAt: info.createdAt,
    updatedAt: localIso(stat.mtime),
    model: info.model,
    originator: null,
    sizeBytes: stat.size,
    remote: false,
    host: null,
    prompts,
    extra: buildExtra(info, projectDir, !info.cwd && Boolean(cwd)),
    duplicateFiles: [],
  }
  return { row, badLines, bytesRead }
}

/** 便宜的存在性探测：根目录下有 jsonl 就算命中，命中即停。 */
export function detect(ctx = {}) {
  const root = resolveRoot(ctx)
  let entries
  try {
    entries = fs.readdirSync(root, { withFileTypes: true })
  } catch {
    return false
  }
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith('.jsonl')) return true
    if (!entry.isDirectory()) continue
    try {
      const inner = fs.readdirSync(path.join(root, entry.name))
      if (inner.some((name) => name.endsWith('.jsonl'))) return true
    } catch {
      // 单个项目目录读不了不影响别的目录
    }
  }
  return false
}

export async function scan(ctx = {}) {
  const started = Date.now()
  const root = resolveRoot(ctx)
  const concurrency =
    Number.isInteger(ctx.concurrency) && ctx.concurrency > 0 ? ctx.concurrency : DEFAULT_CONCURRENCY
  const maxPrompts = Math.min(MAX_PROMPTS, Math.max(1, Number(ctx.maxPrompts) || MAX_PROMPTS))
  const files = walkFiles(root, (name) => name.endsWith('.jsonl'))
  const warnings = []
  const stats = {
    root,
    files: files.length,
    sessions: 0,
    duplicates: 0,
    badLines: 0,
    bytesRead: 0,
    slowestMs: 0,
    slowestFile: null,
    elapsedMs: 0,
  }

  const rows = await mapWithConcurrency(files, concurrency, async (file) => {
    const at = Date.now()
    try {
      const result = await scanFile(file, { maxPrompts, deep: ctx.deep === true })
      const cost = Date.now() - at
      if (cost > stats.slowestMs) {
        stats.slowestMs = cost
        stats.slowestFile = file
      }
      stats.badLines += result.badLines
      stats.bytesRead += result.bytesRead
      return result.row
    } catch (error) {
      // 单个文件坏掉不能让整次扫描失败：其它会话仍然要能用。
      warnings.push(`读取失败：${file}（${error?.code ?? 'EUNKNOWN'} ${error?.message ?? error}）`)
      return null
    }
  })

  // 同一 sessionId 可能被复制到两个项目目录：留更新（mtime 更晚）的那份，
  // 另一份只记路径，否则面板里会出现两条一模一样的会话。
  const byId = new Map()
  for (const row of rows) {
    if (!row) continue
    const existing = byId.get(row.id)
    if (!existing) {
      byId.set(row.id, row)
      continue
    }
    const rowTime = Date.parse(row.updatedAt) || 0
    const existingTime = Date.parse(existing.updatedAt) || 0
    const newer = rowTime > existingTime || (rowTime === existingTime && row.sizeBytes > existing.sizeBytes)
    const winner = newer ? row : existing
    const loser = newer ? existing : row
    winner.duplicateFiles = [...(winner.duplicateFiles ?? []), loser.file, ...(loser.duplicateFiles ?? [])]
    byId.set(winner.id, winner)
    stats.duplicates += 1
  }

  const sessions = [...byId.values()].sort((a, b) =>
    String(b.updatedAt ?? '').localeCompare(String(a.updatedAt ?? '')),
  )
  stats.sessions = sessions.length
  stats.elapsedMs = Date.now() - started
  return { sessions, warnings, stats }
}

