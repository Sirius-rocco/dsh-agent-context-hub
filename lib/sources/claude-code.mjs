/** 解析一行 JSON；BOM 只可能出现在文件第一行，顺手剥掉。 */
function parseLine(line) {
  const text = line.charCodeAt(0) === 0xfeff ? line.slice(1) : line
  try {
    return JSON.parse(text)
  } catch {
    return BAD_LINE
  }
}

/** 内容块 → 纯文本（字符串内容、text 块、tool_result 的数组内容共用）。 */
function contentText(content) {
  if (typeof content === 'string') return content
  if (!Array.isArray(content)) return ''
  const parts = []
  for (const item of content) {
    if (typeof item === 'string') parts.push(item)
    else if (item && typeof item.text === 'string') parts.push(item.text)
  }
  return parts.join('\n')
}

/** 工具结果可能只有图片；没有文本时给一句占位，别让这条输出凭空消失。 */
function toolResultText(content) {
  const text = contentText(content)
  if (text.trim()) return text
  if (Array.isArray(content) && content.some((item) => item?.type === 'image')) return '[图片内容]'
  return ''
}

/** 反复剥掉开头的已知注入块：system-reminder 经常被拼在真实提问前面。 */
function stripInjectionBlocks(text) {
  let rest = String(text ?? '')
  for (;;) {
    const trimmed = rest.trimStart()
    const open = trimmed.match(/^<([a-zA-Z_][\w.-]*)(\s[^>]*)?>/)
    if (!open || !INJECTION_TAGS.includes(open[1])) return rest
    const close = trimmed.indexOf(`</${open[1]}>`)
    if (close === -1) return rest
    rest = trimmed.slice(close + open[1].length + 3)
  }
}

/** 整段都是注入（剥完标签后为空）时返回 true。 */
export function isInjectedText(text) {
  const stripped = stripInjectionBlocks(text).trim()
  if (!stripped) return true
  if (INJECTION_MARKERS.some((marker) => stripped.startsWith(marker))) return true
  if (!stripped.startsWith('<')) return false
  const open = stripped.match(/^<([a-zA-Z_][\w.-]*)/)
  if (open && INJECTION_TAGS.includes(open[1])) return true
  // 整段只有一个标签，例如 <local-command-stdout>…</…> 这类还没进名单的变体。
  return /^<([a-zA-Z_][\w.-]*)(\s[^>]*)?>[\s\S]*<\/\1>\s*$/.test(stripped)
}

/** 一条 user 行里所有可读文本块。 */
function userTexts(message) {
  const content = message?.content
  if (typeof content === 'string') return [content]
  if (!Array.isArray(content)) return []
  const out = []
  for (const item of content) {
    if (typeof item === 'string') out.push(item)
    else if (item?.type === 'text' && typeof item.text === 'string') out.push(item.text)
  }
  return out
}

/**
 * 一行 user 记录里真正的用户输入，压成一行短文本；注入/空串/子代理返回 null。
 * 子代理（isSidechain）的提问是主 agent 生成的提示词，不是人打的字。
 */
function promptText(line) {
  if (line?.isMeta === true || line?.isSidechain === true) return null
  const raw = userTexts(line?.message).join('\n')
  if (isInjectedText(raw)) return null
  const flat = stripInjectionBlocks(raw).replace(/\s+/g, ' ').trim()
  if (!flat) return null
  return flat.length > PROMPT_CHARS ? `${flat.slice(0, PROMPT_CHARS)}…` : flat
}

/** 行里的时间戳统一成本地 ISO：和 updatedAt（文件 mtime）同一格式，排序才不会错位。 */
function normalizeIso(value) {
  if (typeof value !== 'string' || !value) return null
  const time = new Date(value)
  if (Number.isNaN(time.getTime())) return null
  return localIso(time)
}

/**
 * 项目目录名反解 cwd。编码是把 `\` `:` 换成 `-`，所以只能尽力：
 * `-d-work-demo` → `D:\work\demo`，`-Users-alice-proj` → `/Users/alice/proj`。
 * 反解不出来时宁可给 null，也不要编一个假路径。
 */
function cwdFromProjectDir(name) {
  if (!name || !name.startsWith('-')) return null
  const drive = name.match(/^-([a-zA-Z])--?(.+)$/)
  if (drive) return `${drive[1].toUpperCase()}:\\${drive[2].replace(/-/g, '\\')}`
  const posix = name.slice(1)
  return posix ? `/${posix.replace(/-/g, '/')}` : null
}

